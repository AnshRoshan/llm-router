# Feedback samples
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class FeedbackSample:
    features: tuple[float, ...]
    model_id: str
    outcome: float  # 0..1; 0.5 = tie / uncertain


def _outcome(value: Any) -> float:
    if isinstance(value, bool):
        return 1.0 if value else 0.0
    if isinstance(value, (int, float)):
        return min(1.0, max(0.0, float(value)))
    text = str(value).lower()
    if text in ("good", "ok", "win", "correct", "1", "true"):
        return 1.0
    if text in ("bad", "fail", "loss", "wrong", "misrouted", "0", "false"):
        return 0.0
    if text in ("tie", "equal"):
        return 0.5
    raise ValueError(f"unrecognised outcome {value!r}")


def parse_feedback_line(obj: Mapping[str, Any]) -> list[FeedbackSample]:
    """One JSONL line -> zero or more samples. Pairwise rows expand to two."""
    messages = obj.get("messages")
    if messages:
        msgs = tuple(
            Message(str(m.get("role", "user")), str(m.get("content", "")))
            for m in messages
        )
    else:
        text = obj.get("text", obj.get("prompt"))
        if text is None:
            raise ValueError("feedback row needs 'text' or 'messages'")
        msgs = (Message("user", str(text)),)

    workload_raw = obj.get("workload")
    workload = (WorkloadClass(str(workload_raw)) if workload_raw
                else WorkloadClass.CHAT)
    req = RoutingRequest(messages=msgs, workload=workload)
    x = extract_features(req, workload)

    if "winner" in obj:
        a, b = obj.get("model_a"), obj.get("model_b")
        if not a or not b:
            raise ValueError("pairwise rows need model_a and model_b")
        w = str(obj["winner"]).lower()
        y = 1.0 if w in ("a", "model_a") else 0.0 if w in ("b", "model_b") else 0.5
        return [FeedbackSample(x, str(a), y), FeedbackSample(x, str(b), 1.0 - y)]

    model = obj.get("model")
    if not model:
        raise ValueError("feedback row needs 'model' or (model_a/model_b/winner)")
    return [FeedbackSample(x, str(model), _outcome(obj.get("outcome", 1)))]


def load_feedback(path: str) -> list[FeedbackSample]:
    if path == "-":
        raw = sys.stdin.read()
    else:
        with open(path, encoding="utf-8") as f:
            raw = f.read()
    samples: list[FeedbackSample] = []
    for lineno, line in enumerate(raw.splitlines(), start=1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        obj = json.loads(line)
        try:
            samples.extend(parse_feedback_line(obj))
        except (ValueError, KeyError) as exc:
            raise ValueError(f"line {lineno}: {exc}") from exc
    return samples


# --------------------------------------------------------------------------- #
# Training: per-model logistic head, plain SGD, no dependencies
# --------------------------------------------------------------------------- #
def _sigmoid(z: float) -> float:
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


@dataclass(frozen=True)
class HeadReport:
    model_id: str
    samples: int
    mean_outcome: float
    train_accuracy: float
    eval_accuracy: float | None


def train_heads(samples: Sequence[FeedbackSample], *, epochs: int = 200,
                lr: float = 0.25, l2: float = 1e-4, holdout: float = 0.2,
                min_samples: int = 8, seed: int = 13,
                shrinkage_k: float = 20.0,
                ) -> tuple[QualityModel, list[HeadReport]]:
    """Fit one logistic head per model. Models below `min_samples` keep the
    prior untouched — this is why the blend is safe on thin data."""
    by_model: dict[str, list[FeedbackSample]] = {}
    for s in samples:
        by_model.setdefault(s.model_id, []).append(s)

    rng = random.Random(seed)
    heads: dict[str, ModelHead] = {}
    reports: list[HeadReport] = []

    for model_id in sorted(by_model):
        rows = by_model[model_id]
        if len(rows) < min_samples:
            continue
        idx = list(range(len(rows)))
        rng.shuffle(idx)
        n_eval = int(len(rows) * holdout)
        eval_rows = [rows[i] for i in idx[:n_eval]]
        train_rows = [rows[i] for i in idx[n_eval:]]
        if not train_rows:
            continue

        w = [0.0] * N_FEATURES
        b = 0.0
        for _ in range(epochs):
            order = list(range(len(train_rows)))
            rng.shuffle(order)
            for i in order:
                row = train_rows[i]
                z = b
                for j, xj in enumerate(row.features):
                    z += w[j] * xj
                err = _sigmoid(z) - row.outcome
                b -= lr * err
                for j, xj in enumerate(row.features):
                    w[j] -= lr * (err * xj + l2 * w[j])

        def accuracy(rows: Sequence[FeedbackSample]) -> float:
            hits = 0
            for r in rows:
                z = b + sum(wj * xj for wj, xj in zip(w, r.features))
                if (_sigmoid(z) >= 0.5) == (r.outcome >= 0.5):
                    hits += 1
            return hits / len(rows)

        mean_y = sum(r.outcome for r in rows) / len(rows)
        heads[model_id] = ModelHead(bias=b, weights=tuple(w), samples=len(rows))
        reports.append(HeadReport(
            model_id=model_id, samples=len(rows), mean_outcome=mean_y,
            train_accuracy=accuracy(train_rows),
            eval_accuracy=accuracy(eval_rows) if eval_rows else None,
        ))

    return QualityModel(heads, shrinkage_k=shrinkage_k), reports


